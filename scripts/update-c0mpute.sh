#!/bin/sh
# Rewrite Formula/c0mpute.rb for a c0mpute release, from the release's own
# .sha256 files. Usage: scripts/update-c0mpute.sh [version]  (default: latest)
set -eu
cd "$(dirname "$0")/.."
version="${1:-}"
if [ -z "$version" ]; then
  version=$(curl -fsSLI -o /dev/null -w '%{url_effective}' \
    https://github.com/profullstack/c0mpute/releases/latest | sed 's#.*/tag/v##')
fi
version="${version#v}"
base="https://github.com/profullstack/c0mpute/releases/download/v${version}"
sum() { curl -fsSL "${base}/c0mpute-$1.tar.gz.sha256" | awk '{print $1}'; }
mac_arm=$(sum darwin-aarch64)
mac_x86=$(sum darwin-x86_64)
linux_arm=$(sum linux-aarch64)
linux_x86=$(sum linux-x86_64)
for s in "$mac_arm" "$mac_x86" "$linux_arm" "$linux_x86"; do
  printf '%s' "$s" | grep -Eq '^[0-9a-f]{64}$' || { echo "bad sha256 for v${version}: $s" >&2; exit 1; }
done
cat > Formula/c0mpute.rb <<RUBY
# Generated by scripts/update-c0mpute.sh from the release's .sha256 files.
# The update-c0mpute workflow refreshes it when c0mpute publishes a release.
class C0mpute < Formula
  desc "Run a node on the c0mpute decentralized compute network"
  homepage "https://c0mpute.com"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "${base}/c0mpute-darwin-aarch64.tar.gz"
      sha256 "${mac_arm}"
    end
    on_intel do
      url "${base}/c0mpute-darwin-x86_64.tar.gz"
      sha256 "${mac_x86}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/c0mpute-linux-aarch64.tar.gz"
      sha256 "${linux_arm}"
    end
    on_intel do
      url "${base}/c0mpute-linux-x86_64.tar.gz"
      sha256 "${linux_x86}"
    end
  end

  def install
    libexec.install "c0mpute"
    # Homebrew owns the binary, so turn off c0mpute's self-update;
    # \`brew upgrade c0mpute\` updates it instead.
    (bin/"c0mpute").write_env_script libexec/"c0mpute", C0MPUTE_NO_AUTO_UPDATE: "1"
  end

  def caveats
    <<~EOS
      Start a worker in the foreground, or in the background with -d:
        c0mpute worker start
        c0mpute worker start -d

      This formula installs the c0mpute CLI only. For the full node stack
      (coinpay and infernet CLIs, inference payouts), use the installer:
        curl -fsSL https://c0mpute.com/install.sh | sh

      Earnings depend on network demand and vary; see https://c0mpute.com/nodes
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/c0mpute --version")
  end
end
RUBY
echo "Formula/c0mpute.rb -> v${version}"
